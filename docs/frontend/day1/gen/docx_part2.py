def sec_flows(doc):
    h1(doc, "5", "用户流程（F1–F12）")
    para(doc,
         "流程按「谁在什么情况下做什么」编写，每一步都写了系统的判定条件，便于直接转成测试用例。"
         "其中 F1–F8 属 P0 记账闭环，F9–F11 属 P1/P2 干预闭环，F12 是横切所有页面的三态与降级约束。", after=8)

    h2(doc, "5.1", "两条主干闭环")
    para(doc,
         "系统只有两条闭环：一条把「花了钱」变成可读的数据，一条把「想花钱」变成一次有成本的决策。"
         "两者在「买下」处交汇——买下的意图会预填一笔账，让干预结果直接落到账本里。"
         "闭环全貌见 §6 首图 D01（横向整页），下文 F1–F12 为逐步展开。", after=8)

    h2(doc, "5.2", "流程明细")
    for no, name, trigger, pre, steps, fail, end in FLOWS:
        h3(doc, "%s　%s" % (no, name))
        para(doc, "触发：%s　　前置：%s" % (trigger, pre), 8.5, False, INK3, after=4)
        table(doc,
              ["步骤", "页面 / 位置", "用户动作", "系统响应与判定条件"],
              steps, [1.0, 2.9, 5.6, 7.1], size=8)
        cap = "失败与降级：%s　　结束状态：%s" % (fail, end)
        caption(doc, cap, 8, INK3, after=10)
